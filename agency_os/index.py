"""Generate the All Notes Index: one table row per note.

The index is the cheapest way for a session to find anything: one grep of a
single file answers "what do we have on X". It is rebuilt from the notes, so
it is never edited by hand, and its output is deterministic: the ``date`` is
the newest note date rather than today, so regenerating an unchanged vault
produces an identical file and ``--check`` can run in CI.
"""

import os
import re

from .vault import WIKILINK

MAX_SUMMARY = 160


def plain(text):
    """Strip markdown so a summary reads cleanly inside a table cell."""
    text = WIKILINK.sub(lambda m: re.split(r"\\?\|", m.group(2), 1)[-1].split("#")[0].rsplit("/", 1)[-1], text)
    text = re.sub(r"\*\*|__|`", "", text)
    text = re.sub(r"\[([^\]]+)\]\([^)]+\)", r"\1", text)
    text = text.replace("|", "/").strip()
    if len(text) > MAX_SUMMARY:
        text = text[:MAX_SUMMARY].rsplit(" ", 1)[0].rstrip(",.;:") + " ..."
    return text


def folder_code(rel):
    folder = rel.split("/", 1)[0] if "/" in rel else ""
    m = re.match(r"^(\d+)\s*-\s*", folder)
    return m.group(1) if m else folder


def render(vault):
    index_rel = vault.config["index"]
    notes = [n for n in vault.knowledge_notes() if n.rel != index_rel]
    notes.sort(key=lambda n: n.rel.lower())
    dates = [n.date for n in notes if re.match(r"^\d{4}-\d{2}-\d{2}$", n.date)]
    newest = max(dates) if dates else "1970-01-01"
    home = os.path.basename(vault.config["home"])[:-3]
    folders = sorted({n.rel.split("/", 1)[0] for n in notes if "/" in n.rel})
    rows = []
    for n in notes:
        rows.append("| [[{}]] | {} | {} | {} | {} | {} |".format(
            n.name, folder_code(n.rel), n.type, n.status, n.date, plain(n.summary())))
    head = [
        "---",
        "tags: [index, generated]",
        "type: index",
        "date: {}".format(newest),
        "---",
        "",
        "# All Notes Index",
        "",
        "\u2191 [[{}]]".format(home),
        "",
        "Generated by `agency-os index`, do not edit by hand. One row per note ({} notes) "
        "with its folder, type, status, date and one line summary, so a single search of this "
        "file answers \"what do we have on X\".".format(len(rows)),
        "",
        "Folders: " + ", ".join("`{}`".format(f) for f in folders) + ".",
        "",
        "| Note | Folder | Type | Status | Date | Summary |",
        "|---|---|---|---|---|---|",
    ]
    return "\n".join(head + rows) + "\n"


def write_index(vault):
    """Write the index; return ``(path, changed)``."""
    text = render(vault)
    path = vault.path(vault.config["index"])
    old = None
    if os.path.exists(path):
        with open(path, encoding="utf-8") as fh:
            old = fh.read()
    if old == text:
        return path, False
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(text)
    return path, True


def is_current(vault):
    path = vault.path(vault.config["index"])
    if not os.path.exists(path):
        return False
    with open(path, encoding="utf-8") as fh:
        return fh.read() == render(vault)
